import torch
import torch.nn as nn
import torch.nn.functional as F

class GatedWaveNetCPC(nn.Module):
    def __init__(self, in_channels=1, hidden_dim=32, num_layers=10, kernel_size=2,
                 dilation_base=2, use_gru_refiner=True, use_cpc=True, prediction_steps=5):
        super().__init__()
        self.use_gru_refiner = use_gru_refiner
        self.use_cpc = use_cpc
        self.prediction_steps = prediction_steps

        self.res_blocks = nn.ModuleList()
        self.gate_blocks = nn.ModuleList()
        self.skip_blocks = nn.ModuleList()

        for i in range(num_layers):
            dilation = dilation_base ** i
            padding = (kernel_size - 1) * dilation
            in_ch = in_channels if i == 0 else hidden_dim

            self.res_blocks.append(nn.Conv1d(in_ch, hidden_dim, kernel_size, padding=padding, dilation=dilation))
            self.gate_blocks.append(nn.Conv1d(in_ch, hidden_dim, kernel_size, padding=padding, dilation=dilation))
            self.skip_blocks.append(nn.Conv1d(hidden_dim, hidden_dim, 1))

        if self.use_gru_refiner:
            self.refiner = nn.GRU(hidden_dim, hidden_dim, batch_first=True)
        else:
            self.refiner = nn.Conv1d(hidden_dim, hidden_dim, kernel_size=3, padding=1)

        self.output_head = nn.Linear(hidden_dim, 1)

        if self.use_cpc:
            self.context_rnn = nn.GRU(hidden_dim, hidden_dim, batch_first=True)
            self.future_predictors = nn.ModuleList([
                nn.Linear(hidden_dim, hidden_dim) for _ in range(prediction_steps)
            ])

    def forward(self, x):
        skip_sum = None
        for conv_f, conv_g, skip in zip(self.res_blocks, self.gate_blocks, self.skip_blocks):
            f = torch.tanh(conv_f(x))
            g = torch.sigmoid(conv_g(x))
            out = f * g
            out = out[..., :x.shape[-1]]
            skip_out = skip(out)
            skip_sum = skip_out if skip_sum is None else skip_sum + skip_out
            x = x + out if out.shape == x.shape else out

        if self.use_gru_refiner:
            z_seq = skip_sum.permute(0, 2, 1)  # (B, T, C)
            _, h = self.refiner(z_seq)
            out = h[-1]
        else:
            out = self.refiner(skip_sum)
            out = torch.mean(out, dim=2)

        prediction = self.output_head(out).squeeze(1)

        if self.use_cpc:
            z_seq = skip_sum.permute(0, 2, 1)
            c_seq, _ = self.context_rnn(z_seq)
            return prediction, c_seq, z_seq
        else:
            return prediction, None, None

def info_nce_loss(z_context, z_future, future_predictors, K=5):
    loss = 0.0
    for k in range(K):
        if z_context.size(1) <= k + 1:
            continue
        pred = future_predictors[k](z_context[:, :-k-1])
        target = z_future[:, k+1:]
        sim = F.cosine_similarity(pred, target, dim=-1)
        labels = torch.ones_like(sim)
        loss += F.binary_cross_entropy_with_logits(sim, labels)
    return loss / K if K > 0 else torch.tensor(0.0, device=z_context.device)

