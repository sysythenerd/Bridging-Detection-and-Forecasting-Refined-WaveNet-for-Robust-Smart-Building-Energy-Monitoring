            actual_seq = data[i + seq_length:i + seq_length + 2]

            input_tensor = torch.tensor(input_seq, dtype=torch.float32).unsqueeze(0).unsqueeze(-1).to(device)

            step_predictions = []
            for _ in range(2):
                output = model(input_tensor).squeeze().item()
