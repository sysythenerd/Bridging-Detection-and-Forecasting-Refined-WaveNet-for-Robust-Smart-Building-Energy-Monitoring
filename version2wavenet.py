class GatedWaveNet(nn.Module):
    def __init__(self, in_channels=1, hidden_dim=32, num_layers=10, kernel_size=2, dilation_base=2, dropout=0.2):
        super().__init__()
        self.res_blocks = nn.ModuleList()
        self.gate_blocks = nn.ModuleList()
        self.skip_blocks = nn.ModuleList()
        self.dropout_blocks = nn.ModuleList()

        for i in range(num_layers):
            dilation = dilation_base ** i
            padding = (kernel_size - 1) * dilation
            in_ch = in_channels if i == 0 else hidden_dim

            self.res_blocks.append(weight_norm(nn.Conv1d(in_ch, hidden_dim, kernel_size, padding=padding, dilation=dilation)))
            self.gate_blocks.append(weight_norm(nn.Conv1d(in_ch, hidden_dim, kernel_size, padding=padding, dilation=dilation)))
            self.skip_blocks.append(weight_norm(nn.Conv1d(hidden_dim, hidden_dim, 1)))
            self.dropout_blocks.append(nn.Dropout(p=dropout))

        self.output_layer = nn.Linear(hidden_dim, 1)

    def forward(self, x):
        skip_sum = None
        for conv_f, conv_g, skip, drop in zip(self.res_blocks, self.gate_blocks, self.skip_blocks, self.dropout_blocks):
            f = torch.tanh(conv_f(x))
            g = torch.sigmoid(conv_g(x))
            out = drop(f * g)[..., :x.shape[-1]]
            skip_out = skip(out)
            skip_sum = skip_out if skip_sum is None else skip_sum + skip_out
            x = x + out if out.shape == x.shape else out

        out = torch.mean(skip_sum, dim=2)
        return self.output_layer(out).squeeze(1)

